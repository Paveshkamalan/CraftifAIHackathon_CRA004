import time
import argparse
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple
import cv2
import numpy as np
import onnxruntime as ort
import yaml


class PipeGenPipeline:
    """
    Executes the PipeGen-generated vision pipeline with support for
    configurable inference intervals, dynamic resolution scaling,
    ROI filtering, and runtime policy adaptation.
    """

    def __init__(
        self,
        config_path: str = "pipegen_output/generated_pipeline/config.yaml",
        model_path: str = "pipegen_output/generated_pipeline/model.onnx",
        inference_interval: int = 1,
        resolution: str | List[int] = "native",
        roi_mode: str = "full_frame",
    ):
        self.config_path = Path(config_path)
        self.model_path = Path(model_path)
        self.inference_interval = max(1, int(inference_interval))
        self.resolution = resolution
        self.roi_mode = roi_mode

        self.config = self._load_config()
        self.session = self._init_session()

        # Cache for tracking across frames
        self.last_detections: List[Dict[str, Any]] = []
        self.last_mean_confidence: float = 0.0

    def _load_config(self) -> Dict[str, Any]:
        if self.config_path.exists():
            with open(self.config_path, "r", encoding="utf-8") as f:
                return yaml.safe_load(f) or {}
        return {}

    def _init_session(self) -> ort.InferenceSession:
        if not self.model_path.exists():
            raise FileNotFoundError(f"PipeGen model not found at {self.model_path}")

        # Prefer available GPU providers (DmlExecutionProvider, CUDAExecutionProvider)
        available = ort.get_available_providers()
        preferred = []
        for p in ["DmlExecutionProvider", "CUDAExecutionProvider", "CPUExecutionProvider"]:
            if p in available:
                preferred.append(p)
        if not preferred:
            preferred = ["CPUExecutionProvider"]

        for provider_list in [preferred, ["CPUExecutionProvider"]]:
            try:
                return ort.InferenceSession(str(self.model_path), sess_options=opts, providers=provider_list)
            except Exception:
                continue

        # Final fallback
        return ort.InferenceSession(str(self.model_path), providers=["CPUExecutionProvider"])

    def set_inference_interval(self, new_interval: int) -> None:
        """Dynamically update inference interval at runtime."""
        self.inference_interval = max(1, int(new_interval))

    def set_roi_mode(self, new_roi_mode: str) -> None:
        """Dynamically update ROI mode at runtime."""
        self.roi_mode = new_roi_mode

    def preprocess(self, frame: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """
        Resize according to candidate resolution, apply ROI,
        and prepare 640x640 tensor for ONNX inference.
        """
        h_orig, w_orig = frame.shape[:2]

        # Resolution scaling
        if self.resolution != "native" and isinstance(self.resolution, (list, tuple)) and len(self.resolution) == 2:
            target_w, target_h = int(self.resolution[0]), int(self.resolution[1])
            frame = cv2.resize(frame, (target_w, target_h), interpolation=cv2.INTER_LINEAR)

        # ROI mode
        if self.roi_mode == "activity_roi":
            h, w = frame.shape[:2]
            y1, y2 = int(0.20 * h), int(0.85 * h)
            x1, x2 = int(0.20 * w), int(0.80 * w)
            frame = frame[y1:y2, x1:x2]

        # Model input formatting: 640x640 RGB float32 NCHW
        img_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        resized = cv2.resize(img_rgb, (640, 640), interpolation=cv2.INTER_LINEAR)
        blob = (resized.astype(np.float32) / 255.0).transpose(2, 0, 1)
        blob = np.expand_dims(blob, axis=0)
        return frame, blob

    def process_frame(self, frame: np.ndarray, frame_idx: int) -> Dict[str, Any]:
        """
        Process a single frame through the PipeGen pipeline.
        Measures exact per-frame latency and records detection metrics.
        """
        t0 = time.perf_counter()

        processed_frame, blob = self.preprocess(frame)
        should_infer = (frame_idx % self.inference_interval == 0)

        if should_infer:
            outputs = self.session.run(None, {"images": blob})
            boxes, scores, classes = outputs[0][0], outputs[1][0], outputs[2][0]

            conf_thresh = self.config.get("model", {}).get("confidence_threshold", 0.40)
            valid_mask = scores >= conf_thresh
            valid_scores = scores[valid_mask]
            det_count = int(np.sum(valid_mask))
            mean_conf = float(np.mean(valid_scores)) if det_count > 0 else 0.0

            # Store for tracking
            self.last_detections = [
                {"box": boxes[i].tolist(), "score": float(scores[i]), "class": int(classes[i])}
                for i in range(len(scores)) if valid_mask[i]
            ]
            self.last_mean_confidence = mean_conf
        else:
            # Multi-frame tracker reuse (slight temporal decay proxy)
            det_count = len(self.last_detections)
            mean_conf = self.last_mean_confidence * 0.98

        t1 = time.perf_counter()
        latency_ms = (t1 - t0) * 1000.0

        return {
            "frame_idx": frame_idx,
            "latency_ms": latency_ms,
            "inferred": should_infer,
            "detection_count": det_count,
            "mean_confidence": mean_conf,
            "inference_interval": self.inference_interval,
            "roi_mode": self.roi_mode,
        }

    def run(
        self,
        video_path: str,
        duration_seconds: float = 45.0,
        warmup_seconds: float = 5.0,
        callback: Optional[Callable[[Dict[str, Any]], None]] = None,
    ) -> Dict[str, Any]:
        """
        Run the pipeline over the specified input video.
        """
        cap = cv2.VideoCapture(video_path)
        if not cap.isOpened():
            raise RuntimeError(f"Cannot open video source: {video_path}")

        fps_nominal = cap.get(cv2.CAP_PROP_FPS) or 30.0
        total_target_frames = int((duration_seconds + warmup_seconds) * fps_nominal)
        warmup_frames = int(warmup_seconds * fps_nominal)

        frame_idx = 0
        all_latencies_ms: List[float] = []
        confidences: List[float] = []
        detection_counts: List[int] = []

        wall_start = None

        while frame_idx < total_target_frames:
            ret, frame = cap.read()
            if not ret or frame is None:
                # Loop video if benchmark duration exceeds video length
                cap.set(cv2.CAP_PROP_POS_FRAMES, 0)
                ret, frame = cap.read()
                if not ret:
                    break

            # Execute pipeline step
            metrics = self.process_frame(frame, frame_idx)

            # Record metrics only after warmup period
            if frame_idx >= warmup_frames:
                if wall_start is None:
                    wall_start = time.perf_counter()
                all_latencies_ms.append(metrics["latency_ms"])
                confidences.append(metrics["mean_confidence"])
                detection_counts.append(metrics["detection_count"])

                if callback:
                    callback(metrics)

            frame_idx += 1

        cap.release()
        wall_end = time.perf_counter()

        measured_frames = len(all_latencies_ms)
        elapsed_sec = (wall_end - wall_start) if wall_start else 0.001
        fps_actual = measured_frames / elapsed_sec if elapsed_sec > 0 else 0.0

        p50 = float(np.percentile(all_latencies_ms, 50)) if all_latencies_ms else 0.0
        p95 = float(np.percentile(all_latencies_ms, 95)) if all_latencies_ms else 0.0
        mean_conf = float(np.mean(confidences)) if confidences else 0.0
        total_detections = int(np.sum(detection_counts)) if detection_counts else 0

        return {
            "frames_processed": measured_frames,
            "elapsed_seconds": round(elapsed_sec, 3),
            "fps": round(fps_actual, 2),
            "p50_latency_ms": round(p50, 2),
            "p95_latency_ms": round(p95, 2),
            "mean_confidence": round(mean_conf, 4),
            "detection_count": total_detections,
            "latencies_ms": all_latencies_ms,
        }
